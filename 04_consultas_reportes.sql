-- 1. PRODUCTOS CON BAJO STOCK

SELECT
    P.ID_PRODUCTO,
    P.NOMBRE AS PRODUCTO,
    I.STOCK_ACTUAL,
    I.STOCK_MINIMO
FROM INVENTARIO_FACTURACION.PRODUCTO P
INNER JOIN INVENTARIO_FACTURACION.INVENTARIO I
    ON I.ID_PRODUCTO = P.ID_PRODUCTO
WHERE I.STOCK_ACTUAL <= I.STOCK_MINIMO
ORDER BY I.STOCK_ACTUAL;

-- 2. PRODUCTOS CON CATEGORIA Y PROVEEDOR

SELECT DISTINCT
    P.ID_PRODUCTO,
    P.CODIGO_BARRAS,
    P.NOMBRE AS PRODUCTO,
    C.NOMBRE AS CATEGORIA,
    PR.NOMBRE AS PROVEEDOR,
    P.PRECIO_COMPRA,
    P.PRECIO_VENTA
FROM INVENTARIO_FACTURACION.PRODUCTO P
INNER JOIN INVENTARIO_FACTURACION.CATEGORIA C
    ON C.ID_CATEGORIA = P.ID_CATEGORIA
LEFT JOIN INVENTARIO_FACTURACION.DETALLE_COMPRA DC
    ON DC.ID_PRODUCTO = P.ID_PRODUCTO
LEFT JOIN INVENTARIO_FACTURACION.COMPRA CO
    ON CO.ID_COMPRA = DC.ID_COMPRA
LEFT JOIN INVENTARIO_FACTURACION.PROVEEDOR PR
    ON PR.ID_PROVEEDOR = CO.ID_PROVEEDOR
ORDER BY P.ID_PRODUCTO;

-- 3. FACTURA COMPLETA

SELECT
    F.NUMERO_FACTURA,
    F.FECHA_EMISION,
    C.NOMBRE AS CLIENTE,
    P.NOMBRE AS PRODUCTO,
    DF.CANTIDAD,
    DF.PRECIO_UNITARIO,
    DF.SUBTOTAL,
    F.TOTAL
FROM INVENTARIO_FACTURACION.FACTURA F
LEFT JOIN INVENTARIO_FACTURACION.CLIENTE C
    ON C.ID_CLIENTE = F.ID_CLIENTE
INNER JOIN INVENTARIO_FACTURACION.DETALLE_FACTURA DF
    ON DF.ID_FACTURA = F.ID_FACTURA
INNER JOIN INVENTARIO_FACTURACION.PRODUCTO P
    ON P.ID_PRODUCTO = DF.ID_PRODUCTO
ORDER BY F.ID_FACTURA, DF.ID_DETALLE;

-- 4. VENTAS TOTALES POR CLIENTE

SELECT
    C.ID_CLIENTE,
    C.NOMBRE AS CLIENTE,
    COUNT(F.ID_FACTURA) AS TOTAL_FACTURAS,
    NVL(SUM(F.TOTAL),0) AS TOTAL_COMPRADO
FROM INVENTARIO_FACTURACION.CLIENTE C
LEFT JOIN INVENTARIO_FACTURACION.FACTURA F
    ON F.ID_CLIENTE = C.ID_CLIENTE
GROUP BY C.ID_CLIENTE, C.NOMBRE
ORDER BY TOTAL_COMPRADO DESC;

-- 5. VENTAS POR PRODUCTO

SELECT
    P.ID_PRODUCTO,
    P.NOMBRE AS PRODUCTO,
    SUM(DF.CANTIDAD) AS CANTIDAD_VENDIDA,
    SUM(DF.SUBTOTAL) AS INGRESO_GENERADO
FROM INVENTARIO_FACTURACION.PRODUCTO P
INNER JOIN INVENTARIO_FACTURACION.DETALLE_FACTURA DF
    ON DF.ID_PRODUCTO = P.ID_PRODUCTO
GROUP BY P.ID_PRODUCTO, P.NOMBRE
ORDER BY CANTIDAD_VENDIDA DESC;

-- 6. COMPRAS POR PROVEEDOR

SELECT
    PR.ID_PROVEEDOR,
    PR.NOMBRE AS PROVEEDOR,
    COUNT(C.ID_COMPRA) AS TOTAL_COMPRAS,
    NVL(SUM(C.TOTAL),0) AS MONTO_TOTAL
FROM INVENTARIO_FACTURACION.PROVEEDOR PR
LEFT JOIN INVENTARIO_FACTURACION.COMPRA C
    ON C.ID_PROVEEDOR = PR.ID_PROVEEDOR
GROUP BY PR.ID_PROVEEDOR, PR.NOMBRE
ORDER BY MONTO_TOTAL DESC;

-- 7. PRODUCTOS NUNCA VENDIDOS

SELECT
    P.ID_PRODUCTO,
    P.NOMBRE AS PRODUCTO
FROM INVENTARIO_FACTURACION.PRODUCTO P
WHERE NOT EXISTS (
    SELECT 1
    FROM INVENTARIO_FACTURACION.DETALLE_FACTURA DF
    WHERE DF.ID_PRODUCTO = P.ID_PRODUCTO
)
ORDER BY P.ID_PRODUCTO;

-- 8. PRODUCTOS CON VENTAS SUPERIORES AL PROMEDIO

SELECT
    P.NOMBRE AS PRODUCTO,
    SUM(DF.CANTIDAD) AS CANTIDAD_VENDIDA
FROM INVENTARIO_FACTURACION.PRODUCTO P
INNER JOIN INVENTARIO_FACTURACION.DETALLE_FACTURA DF
    ON DF.ID_PRODUCTO = P.ID_PRODUCTO
GROUP BY P.NOMBRE
HAVING SUM(DF.CANTIDAD) >
       (
           SELECT AVG(TOTAL_PRODUCTO)
           FROM (
               SELECT SUM(CANTIDAD) AS TOTAL_PRODUCTO
               FROM INVENTARIO_FACTURACION.DETALLE_FACTURA
               GROUP BY ID_PRODUCTO
           )
       )
ORDER BY CANTIDAD_VENDIDA DESC;

-- 9. VENTAS POR RANGO DE FECHAS

SELECT
    TRUNC(F.FECHA_EMISION) AS FECHA,
    COUNT(F.ID_FACTURA) AS FACTURAS,
    SUM(F.TOTAL) AS TOTAL_VENDIDO
FROM INVENTARIO_FACTURACION.FACTURA F
WHERE F.FECHA_EMISION BETWEEN
      TIMESTAMP '2026-10-01 00:00:00'
      AND TIMESTAMP '2026-10-31 23:59:59'
GROUP BY TRUNC(F.FECHA_EMISION)
ORDER BY FECHA;

-- 10. KARDEX

SELECT
    MI.FECHA_HORA,
    P.NOMBRE AS PRODUCTO,
    A.NOMBRE AS ALMACEN,
    MI.TIPO,
    MI.CANTIDAD,
    MI.REFERENCIA
FROM INVENTARIO_FACTURACION.MOVIMIENTO_INVENTARIO MI
INNER JOIN INVENTARIO_FACTURACION.PRODUCTO P
    ON P.ID_PRODUCTO = MI.ID_PRODUCTO
INNER JOIN INVENTARIO_FACTURACION.ALMACEN A
    ON A.ID_ALMACEN = MI.ID_ALMACEN
ORDER BY MI.FECHA_HORA;

-- 11. CIERRE DE CAJA

SELECT
    MP.NOMBRE AS METODO_PAGO,
    COUNT(F.ID_FACTURA) AS NUMERO_FACTURAS,
    SUM(F.TOTAL) AS MONTO_COBRADO
FROM INVENTARIO_FACTURACION.FACTURA F
INNER JOIN INVENTARIO_FACTURACION.METODO_PAGO MP
    ON MP.ID_METODO_PAGO = F.ID_METODO_PAGO
WHERE F.ESTADO = 'PAGADO'
GROUP BY MP.NOMBRE
ORDER BY MONTO_COBRADO DESC;
