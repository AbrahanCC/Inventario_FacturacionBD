-- 1. CONTROL DE STOCK PREVENTIVO

CREATE OR REPLACE TRIGGER INVENTARIO_FACTURACION.TRG_STOCK_VENTA
BEFORE INSERT OR UPDATE OF CANTIDAD, ID_PRODUCTO, ID_ALMACEN
ON INVENTARIO_FACTURACION.DETALLE_FACTURA
FOR EACH ROW
DECLARE
    V_STOCK NUMBER;
BEGIN
    SELECT STOCK_ACTUAL
    INTO V_STOCK
    FROM INVENTARIO_FACTURACION.INVENTARIO
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
      AND ID_ALMACEN = :NEW.ID_ALMACEN;

    IF :NEW.CANTIDAD > V_STOCK THEN
        RAISE_APPLICATION_ERROR(
            -20010,
            'Venta rechazada: la cantidad solicitada supera el stock disponible.'
        );
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20011,
            'No existe inventario para el producto en el almacen seleccionado.'
        );
END;



-- 2. CALCULO DINAMICO TOTAL FACTURA

CREATE OR REPLACE TRIGGER INVENTARIO_FACTURACION.TRG_TOTAL_FACTURA
FOR INSERT OR UPDATE OR DELETE
ON INVENTARIO_FACTURACION.DETALLE_FACTURA
COMPOUND TRIGGER

    TYPE T_IDS IS TABLE OF NUMBER INDEX BY VARCHAR2(50);
    V_FACTURAS T_IDS;

    AFTER EACH ROW IS
    BEGIN
        IF INSERTING OR UPDATING THEN
            V_FACTURAS(TO_CHAR(:NEW.ID_FACTURA)) := :NEW.ID_FACTURA;
        END IF;

        IF DELETING OR UPDATING THEN
            V_FACTURAS(TO_CHAR(:OLD.ID_FACTURA)) := :OLD.ID_FACTURA;
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        V_CLAVE VARCHAR2(50);
        V_TOTAL NUMBER(12,2);
    BEGIN
        V_CLAVE := V_FACTURAS.FIRST;

        WHILE V_CLAVE IS NOT NULL LOOP

            SELECT NVL(SUM(SUBTOTAL), 0)
            INTO V_TOTAL
            FROM INVENTARIO_FACTURACION.DETALLE_FACTURA
            WHERE ID_FACTURA = V_FACTURAS(V_CLAVE);

            IF V_TOTAL > 0 THEN
                UPDATE INVENTARIO_FACTURACION.FACTURA
                SET TOTAL = V_TOTAL
                WHERE ID_FACTURA = V_FACTURAS(V_CLAVE);
            END IF;

            V_CLAVE := V_FACTURAS.NEXT(V_CLAVE);

        END LOOP;
    END AFTER STATEMENT;

END TRG_TOTAL_FACTURA;

-- 3. CALCULO DINAMICO TOTAL COMPRA

CREATE OR REPLACE TRIGGER INVENTARIO_FACTURACION.TRG_TOTAL_COMPRA
AFTER INSERT OR UPDATE OR DELETE
ON INVENTARIO_FACTURACION.DETALLE_COMPRA
BEGIN

    UPDATE INVENTARIO_FACTURACION.COMPRA C
    SET C.TOTAL = (
        SELECT SUM(DC.SUBTOTAL)
        FROM INVENTARIO_FACTURACION.DETALLE_COMPRA DC
        WHERE DC.ID_COMPRA = C.ID_COMPRA
    )
    WHERE EXISTS (
        SELECT 1
        FROM INVENTARIO_FACTURACION.DETALLE_COMPRA DC
        WHERE DC.ID_COMPRA = C.ID_COMPRA
    );

END;
