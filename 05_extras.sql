    OBJECT_NAME,
    OBJECT_TYPE,
    STATUS
FROM ALL_OBJECTS
WHERE OWNER = 'INVENTARIO_FACTURACION'
  AND OBJECT_TYPE IN ('PROCEDURE','TRIGGER','VIEW')
ORDER BY OBJECT_TYPE, OBJECT_NAME;
