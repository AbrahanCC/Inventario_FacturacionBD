-- 2. PROCEDIMIENTO DE VENTA

CREATE OR REPLACE PROCEDURE INVENTARIO_FACTURACION.PR_REGISTRAR_VENTA (
    P_NUMERO_FACTURA  IN VARCHAR2,
    P_ID_CLIENTE      IN NUMBER,
    P_ID_EMPLEADO     IN NUMBER,
    P_ID_SUCURSAL     IN NUMBER,
    P_ID_METODO_PAGO  IN NUMBER,
    P_ID_PRODUCTO     IN NUMBER,
    P_ID_ALMACEN      IN NUMBER,
    P_CANTIDAD        IN NUMBER
)
AS
    V_ID_FACTURA NUMBER;
    V_ID_DETALLE NUMBER;
    V_PRECIO NUMBER(10,2);
    V_STOCK NUMBER;
    V_SUBTOTAL NUMBER(12,2);
    V_IMPUESTO NUMBER(12,2);
    V_TOTAL NUMBER(12,2);
BEGIN
    IF P_CANTIDAD <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'La cantidad debe ser mayor a cero.');
    END IF;

    SELECT PRECIO_VENTA
    INTO V_PRECIO
    FROM INVENTARIO_FACTURACION.PRODUCTO
    WHERE ID_PRODUCTO = P_ID_PRODUCTO
      AND ESTADO = 'ACTIVO';

    SELECT STOCK_ACTUAL
    INTO V_STOCK
    FROM INVENTARIO_FACTURACION.INVENTARIO
    WHERE ID_PRODUCTO = P_ID_PRODUCTO
      AND ID_ALMACEN = P_ID_ALMACEN
    FOR UPDATE;

    IF P_CANTIDAD > V_STOCK THEN
        RAISE_APPLICATION_ERROR(-20002, 'Stock insuficiente para realizar la venta.');
    END IF;

    V_SUBTOTAL := P_CANTIDAD * V_PRECIO;
    V_IMPUESTO := ROUND(V_SUBTOTAL * 0.12, 2);
    V_TOTAL := V_SUBTOTAL + V_IMPUESTO;

    V_ID_FACTURA := INVENTARIO_FACTURACION.SEQ_FACTURA.NEXTVAL;
    V_ID_DETALLE := INVENTARIO_FACTURACION.SEQ_DETALLE_FACTURA.NEXTVAL;

    INSERT INTO INVENTARIO_FACTURACION.FACTURA
    (ID_FACTURA, NUMERO_FACTURA, FECHA_EMISION, ID_CLIENTE,
     ID_EMPLEADO, ID_SUCURSAL, ID_METODO_PAGO, TOTAL, ESTADO)
    VALUES
    (V_ID_FACTURA, P_NUMERO_FACTURA, CURRENT_TIMESTAMP, P_ID_CLIENTE,
     P_ID_EMPLEADO, P_ID_SUCURSAL, P_ID_METODO_PAGO, V_TOTAL, 'PAGADO');

    INSERT INTO INVENTARIO_FACTURACION.DETALLE_FACTURA
    (ID_DETALLE, ID_FACTURA, ID_PRODUCTO, ID_ALMACEN,
     CANTIDAD, PRECIO_UNITARIO, SUBTOTAL)
    VALUES
    (V_ID_DETALLE, V_ID_FACTURA, P_ID_PRODUCTO, P_ID_ALMACEN,
     P_CANTIDAD, V_PRECIO, V_SUBTOTAL);

    UPDATE INVENTARIO_FACTURACION.INVENTARIO
    SET STOCK_ACTUAL = STOCK_ACTUAL - P_CANTIDAD
    WHERE ID_PRODUCTO = P_ID_PRODUCTO
      AND ID_ALMACEN = P_ID_ALMACEN;

    INSERT INTO INVENTARIO_FACTURACION.MOVIMIENTO_INVENTARIO
    (ID_MOVIMIENTO, ID_PRODUCTO, ID_ALMACEN, ID_EMPLEADO,
     FECHA_HORA, TIPO, CANTIDAD, REFERENCIA)
    VALUES
    (INVENTARIO_FACTURACION.SEQ_MOVIMIENTO.NEXTVAL,
     P_ID_PRODUCTO, P_ID_ALMACEN, P_ID_EMPLEADO,
     CURRENT_TIMESTAMP, 'VENTA', P_CANTIDAD, P_NUMERO_FACTURA);

    COMMIT;
END;
/

-- 3. PROCEDIMIENTO DE COMPRA

CREATE OR REPLACE PROCEDURE INVENTARIO_FACTURACION.PR_REGISTRAR_COMPRA (
    P_NUMERO_COMPRA   IN VARCHAR2,
    P_ID_PROVEEDOR    IN NUMBER,
    P_ID_ALMACEN      IN NUMBER,
    P_ID_EMPLEADO     IN NUMBER,
    P_ID_PRODUCTO     IN NUMBER,
    P_CANTIDAD        IN NUMBER,
    P_COSTO_UNITARIO  IN NUMBER
)
AS
    V_ID_COMPRA NUMBER;
    V_ID_DETALLE NUMBER;
    V_TOTAL NUMBER(12,2);
    V_EXISTE NUMBER;
BEGIN
    IF P_CANTIDAD <= 0 OR P_COSTO_UNITARIO <= 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Cantidad y costo deben ser mayores a cero.');
    END IF;

    V_TOTAL := P_CANTIDAD * P_COSTO_UNITARIO;
    V_ID_COMPRA := INVENTARIO_FACTURACION.SEQ_COMPRA.NEXTVAL;
    V_ID_DETALLE := INVENTARIO_FACTURACION.SEQ_DETALLE_COMPRA.NEXTVAL;

    INSERT INTO INVENTARIO_FACTURACION.COMPRA
    (ID_COMPRA, NUMERO_COMPRA, FECHA_COMPRA, ID_PROVEEDOR,
     ID_ALMACEN, ID_EMPLEADO, TOTAL, ESTADO)
    VALUES
    (V_ID_COMPRA, P_NUMERO_COMPRA, CURRENT_TIMESTAMP, P_ID_PROVEEDOR,
     P_ID_ALMACEN, P_ID_EMPLEADO, V_TOTAL, 'RECIBIDA');

    INSERT INTO INVENTARIO_FACTURACION.DETALLE_COMPRA
    (ID_DETALLE_COMPRA, ID_COMPRA, ID_PRODUCTO, CANTIDAD,
     COSTO_UNITARIO, SUBTOTAL)
    VALUES
    (V_ID_DETALLE, V_ID_COMPRA, P_ID_PRODUCTO, P_CANTIDAD,
     P_COSTO_UNITARIO, V_TOTAL);

    SELECT COUNT(*)
    INTO V_EXISTE
    FROM INVENTARIO_FACTURACION.INVENTARIO
    WHERE ID_PRODUCTO = P_ID_PRODUCTO
      AND ID_ALMACEN = P_ID_ALMACEN;

    IF V_EXISTE = 0 THEN
        INSERT INTO INVENTARIO_FACTURACION.INVENTARIO
        (ID_INVENTARIO, ID_PRODUCTO, ID_ALMACEN, STOCK_ACTUAL, STOCK_MINIMO)
        VALUES
        ((SELECT NVL(MAX(ID_INVENTARIO),0)+1
          FROM INVENTARIO_FACTURACION.INVENTARIO),
         P_ID_PRODUCTO, P_ID_ALMACEN, P_CANTIDAD, 5);
    ELSE
        UPDATE INVENTARIO_FACTURACION.INVENTARIO
        SET STOCK_ACTUAL = STOCK_ACTUAL + P_CANTIDAD
        WHERE ID_PRODUCTO = P_ID_PRODUCTO
          AND ID_ALMACEN = P_ID_ALMACEN;
    END IF;

    INSERT INTO INVENTARIO_FACTURACION.MOVIMIENTO_INVENTARIO
    (ID_MOVIMIENTO, ID_PRODUCTO, ID_ALMACEN, ID_EMPLEADO,
     FECHA_HORA, TIPO, CANTIDAD, REFERENCIA)
    VALUES
    (INVENTARIO_FACTURACION.SEQ_MOVIMIENTO.NEXTVAL,
     P_ID_PRODUCTO, P_ID_ALMACEN, P_ID_EMPLEADO,
     CURRENT_TIMESTAMP, 'COMPRA', P_CANTIDAD, P_NUMERO_COMPRA);

    COMMIT;
END;
/

-- 4. TRIGGER DE STOCK

CREATE OR REPLACE TRIGGER INVENTARIO_FACTURACION.TRG_STOCK_VENTA
BEFORE INSERT OR UPDATE OF CANTIDAD, ID_PRODUCTO, ID_ALMACEN
ON INVENTARIO_FACTURACION.DETALLE_FACTURA
FOR EACH ROW
DECLARE
    V_STOCK NUMBER;
BEGIN
    SELECT STOCK_ACTUAL
    INTO V_STOCK
    FROM INVENTARIO_FACTURACION.INVENTARIO
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
      AND ID_ALMACEN = :NEW.ID_ALMACEN;

    IF :NEW.CANTIDAD > V_STOCK THEN
        RAISE_APPLICATION_ERROR(
            -20010,
            'Venta rechazada: cantidad solicitada supera el stock disponible.'
        );
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20011,
            'No existe inventario para el producto en el almacen seleccionado.'
        );
END;
/

-- 5. TRIGGER DE SUBTOTAL

CREATE OR REPLACE TRIGGER INVENTARIO_FACTURACION.TRG_TOTAL_DETALLE_FACTURA
BEFORE INSERT OR UPDATE
ON INVENTARIO_FACTURACION.DETALLE_FACTURA
FOR EACH ROW
BEGIN
    :NEW.SUBTOTAL := :NEW.CANTIDAD * :NEW.PRECIO_UNITARIO;
END;
/

-- 6. VISTA DE OPERACIONES

CREATE OR REPLACE VIEW INVENTARIO_FACTURACION.VW_HISTORIAL_OPERACIONES AS
SELECT
    'VENTA' AS TIPO_OPERACION,
    F.NUMERO_FACTURA AS DOCUMENTO,
    F.FECHA_EMISION AS FECHA,
    C.NOMBRE AS TERCERO,
    P.NOMBRE AS PRODUCTO,
    DF.CANTIDAD,
    DF.SUBTOTAL AS MONTO
FROM INVENTARIO_FACTURACION.FACTURA F
LEFT JOIN INVENTARIO_FACTURACION.CLIENTE C
    ON C.ID_CLIENTE = F.ID_CLIENTE
INNER JOIN INVENTARIO_FACTURACION.DETALLE_FACTURA DF
    ON DF.ID_FACTURA = F.ID_FACTURA
INNER JOIN INVENTARIO_FACTURACION.PRODUCTO P
    ON P.ID_PRODUCTO = DF.ID_PRODUCTO

UNION ALL

SELECT
    'COMPRA' AS TIPO_OPERACION,
    CO.NUMERO_COMPRA AS DOCUMENTO,
    CO.FECHA_COMPRA AS FECHA,
    PR.NOMBRE AS TERCERO,
    P.NOMBRE AS PRODUCTO,
    DC.CANTIDAD,
    DC.SUBTOTAL AS MONTO
FROM INVENTARIO_FACTURACION.COMPRA CO
INNER JOIN INVENTARIO_FACTURACION.PROVEEDOR PR
    ON PR.ID_PROVEEDOR = CO.ID_PROVEEDOR
INNER JOIN INVENTARIO_FACTURACION.DETALLE_COMPRA DC
    ON DC.ID_COMPRA = CO.ID_COMPRA
INNER JOIN INVENTARIO_FACTURACION.PRODUCTO P
    ON P.ID_PRODUCTO = DC.ID_PRODUCTO;

-- 7. VISTA DE INVENTARIO CRITICO

CREATE OR REPLACE VIEW INVENTARIO_FACTURACION.VW_INVENTARIO_CRITICO AS
SELECT
    P.ID_PRODUCTO,
    P.CODIGO_BARRAS,
    P.NOMBRE AS PRODUCTO,
    A.NOMBRE AS ALMACEN,
    S.NOMBRE AS SUCURSAL,
    I.STOCK_ACTUAL,
    I.STOCK_MINIMO
FROM INVENTARIO_FACTURACION.INVENTARIO I
INNER JOIN INVENTARIO_FACTURACION.PRODUCTO P
    ON P.ID_PRODUCTO = I.ID_PRODUCTO
INNER JOIN INVENTARIO_FACTURACION.ALMACEN A
    ON A.ID_ALMACEN = I.ID_ALMACEN
INNER JOIN INVENTARIO_FACTURACION.SUCURSAL S
    ON S.ID_SUCURSAL = A.ID_SUCURSAL
WHERE I.STOCK_ACTUAL <= I.STOCK_MINIMO;

-- 8. VERIFICAR OBJETOS

