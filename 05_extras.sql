-- 2. PROCEDIMIENTO DE COMPRA

CREATE OR REPLACE PROCEDURE INVENTARIO_FACTURACION.PR_REGISTRAR_COMPRA (
    P_NUMERO_COMPRA   IN VARCHAR2,
    P_ID_PROVEEDOR    IN NUMBER,
    P_ID_ALMACEN      IN NUMBER,
    P_ID_EMPLEADO     IN NUMBER,
    P_ID_PRODUCTO     IN NUMBER,
    P_CANTIDAD        IN NUMBER,
    P_COSTO_UNITARIO  IN NUMBER
)
AS
    V_ID_COMPRA NUMBER;
    V_ID_DETALLE NUMBER;
    V_TOTAL NUMBER(12,2);
    V_EXISTE NUMBER;
BEGIN
    IF P_CANTIDAD <= 0 OR P_COSTO_UNITARIO <= 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Cantidad y costo deben ser mayores a cero.');
    END IF;

    V_TOTAL := P_CANTIDAD * P_COSTO_UNITARIO;
    V_ID_COMPRA := INVENTARIO_FACTURACION.SEQ_COMPRA.NEXTVAL;
    V_ID_DETALLE := INVENTARIO_FACTURACION.SEQ_DETALLE_COMPRA.NEXTVAL;

    INSERT INTO INVENTARIO_FACTURACION.COMPRA
    (ID_COMPRA, NUMERO_COMPRA, FECHA_COMPRA, ID_PROVEEDOR,
     ID_ALMACEN, ID_EMPLEADO, TOTAL, ESTADO)
    VALUES
    (V_ID_COMPRA, P_NUMERO_COMPRA, CURRENT_TIMESTAMP, P_ID_PROVEEDOR,
     P_ID_ALMACEN, P_ID_EMPLEADO, V_TOTAL, 'RECIBIDA');

    INSERT INTO INVENTARIO_FACTURACION.DETALLE_COMPRA
    (ID_DETALLE_COMPRA, ID_COMPRA, ID_PRODUCTO, CANTIDAD,
     COSTO_UNITARIO, SUBTOTAL)
    VALUES
    (V_ID_DETALLE, V_ID_COMPRA, P_ID_PRODUCTO, P_CANTIDAD,
     P_COSTO_UNITARIO, V_TOTAL);

    SELECT COUNT(*)
    INTO V_EXISTE
    FROM INVENTARIO_FACTURACION.INVENTARIO
    WHERE ID_PRODUCTO = P_ID_PRODUCTO
      AND ID_ALMACEN = P_ID_ALMACEN;

    IF V_EXISTE = 0 THEN
        INSERT INTO INVENTARIO_FACTURACION.INVENTARIO
        (ID_INVENTARIO, ID_PRODUCTO, ID_ALMACEN, STOCK_ACTUAL, STOCK_MINIMO)
        VALUES
        ((SELECT NVL(MAX(ID_INVENTARIO),0)+1
          FROM INVENTARIO_FACTURACION.INVENTARIO),
         P_ID_PRODUCTO, P_ID_ALMACEN, P_CANTIDAD, 5);
    ELSE
        UPDATE INVENTARIO_FACTURACION.INVENTARIO
        SET STOCK_ACTUAL = STOCK_ACTUAL + P_CANTIDAD
        WHERE ID_PRODUCTO = P_ID_PRODUCTO
          AND ID_ALMACEN = P_ID_ALMACEN;
    END IF;

    INSERT INTO INVENTARIO_FACTURACION.MOVIMIENTO_INVENTARIO
    (ID_MOVIMIENTO, ID_PRODUCTO, ID_ALMACEN, ID_EMPLEADO,
     FECHA_HORA, TIPO, CANTIDAD, REFERENCIA)
    VALUES
    (INVENTARIO_FACTURACION.SEQ_MOVIMIENTO.NEXTVAL,
     P_ID_PRODUCTO, P_ID_ALMACEN, P_ID_EMPLEADO,
     CURRENT_TIMESTAMP, 'COMPRA', P_CANTIDAD, P_NUMERO_COMPRA);

    COMMIT;
END;
