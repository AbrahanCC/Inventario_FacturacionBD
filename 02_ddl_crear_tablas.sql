-- 1. SUCURSAL

CREATE TABLE INVENTARIO_FACTURACION.SUCURSAL (
    ID_SUCURSAL NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(200) NOT NULL,
    TELEFONO VARCHAR2(20),
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT CHK_SUCURSAL_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);

-- 2. CATEGORIA

CREATE TABLE INVENTARIO_FACTURACION.CATEGORIA (
    ID_CATEGORIA NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(200)
);

-- 3. PROVEEDOR

CREATE TABLE INVENTARIO_FACTURACION.PROVEEDOR (
    ID_PROVEEDOR NUMBER PRIMARY KEY,
    NIT VARCHAR2(20) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(120) NOT NULL,
    TELEFONO VARCHAR2(20),
    CORREO VARCHAR2(100) UNIQUE,
    DIRECCION VARCHAR2(200)
);

-- 4. CLIENTE

CREATE TABLE INVENTARIO_FACTURACION.CLIENTE (
    ID_CLIENTE NUMBER PRIMARY KEY,
    NIT VARCHAR2(20) UNIQUE,
    NOMBRE VARCHAR2(120) NOT NULL,
    TELEFONO VARCHAR2(20),
    CORREO VARCHAR2(100) UNIQUE
);

-- 5. METODO DE PAGO

CREATE TABLE INVENTARIO_FACTURACION.METODO_PAGO (
    ID_METODO_PAGO NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL UNIQUE,
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT CHK_METODO_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);

-- 6. ALMACEN

CREATE TABLE INVENTARIO_FACTURACION.ALMACEN (
    ID_ALMACEN NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    UBICACION VARCHAR2(200),
    ID_SUCURSAL NUMBER NOT NULL,
    CONSTRAINT FK_ALMACEN_SUCURSAL FOREIGN KEY (ID_SUCURSAL)
        REFERENCES INVENTARIO_FACTURACION.SUCURSAL(ID_SUCURSAL)
);

-- 7. EMPLEADO

CREATE TABLE INVENTARIO_FACTURACION.EMPLEADO (
    ID_EMPLEADO NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(120) NOT NULL,
    CORREO VARCHAR2(100) UNIQUE,
    PUESTO VARCHAR2(60) NOT NULL,
    ID_SUCURSAL NUMBER NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_EMPLEADO_SUCURSAL FOREIGN KEY (ID_SUCURSAL)
        REFERENCES INVENTARIO_FACTURACION.SUCURSAL(ID_SUCURSAL),
    CONSTRAINT CHK_EMPLEADO_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);

-- 8. PRODUCTO

CREATE TABLE INVENTARIO_FACTURACION.PRODUCTO (
    ID_PRODUCTO NUMBER PRIMARY KEY,
    CODIGO_BARRAS VARCHAR2(50) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(120) NOT NULL,
    DESCRIPCION VARCHAR2(255),
    PRECIO_COMPRA NUMBER(10,2) NOT NULL,
    PRECIO_VENTA NUMBER(10,2) NOT NULL,
    ID_CATEGORIA NUMBER NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
        REFERENCES INVENTARIO_FACTURACION.CATEGORIA(ID_CATEGORIA),
    CONSTRAINT CHK_PRODUCTO_COMPRA CHECK (PRECIO_COMPRA > 0),
    CONSTRAINT CHK_PRODUCTO_VENTA CHECK (PRECIO_VENTA > 0),
    CONSTRAINT CHK_PRODUCTO_ESTADO CHECK (ESTADO IN ('ACTIVO','INACTIVO'))
);

-- 9. INVENTARIO

CREATE TABLE INVENTARIO_FACTURACION.INVENTARIO (
    ID_INVENTARIO NUMBER PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL,
    ID_ALMACEN NUMBER NOT NULL,
    STOCK_ACTUAL NUMBER DEFAULT 0 NOT NULL,
    STOCK_MINIMO NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT FK_INVENTARIO_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES INVENTARIO_FACTURACION.PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_INVENTARIO_ALMACEN FOREIGN KEY (ID_ALMACEN)
        REFERENCES INVENTARIO_FACTURACION.ALMACEN(ID_ALMACEN),
    CONSTRAINT UQ_PRODUCTO_ALMACEN UNIQUE (ID_PRODUCTO, ID_ALMACEN),
    CONSTRAINT CHK_STOCK_ACTUAL CHECK (STOCK_ACTUAL >= 0),
    CONSTRAINT CHK_STOCK_MINIMO CHECK (STOCK_MINIMO >= 0)
);

-- 10. COMPRA

CREATE TABLE INVENTARIO_FACTURACION.COMPRA (
    ID_COMPRA NUMBER PRIMARY KEY,
    NUMERO_COMPRA VARCHAR2(30) NOT NULL UNIQUE,
    FECHA_COMPRA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ID_PROVEEDOR NUMBER NOT NULL,
    ID_ALMACEN NUMBER NOT NULL,
    ID_EMPLEADO NUMBER NOT NULL,
    TOTAL NUMBER(12,2) NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_COMPRA_PROVEEDOR FOREIGN KEY (ID_PROVEEDOR)
        REFERENCES INVENTARIO_FACTURACION.PROVEEDOR(ID_PROVEEDOR),
    CONSTRAINT FK_COMPRA_ALMACEN FOREIGN KEY (ID_ALMACEN)
        REFERENCES INVENTARIO_FACTURACION.ALMACEN(ID_ALMACEN),
    CONSTRAINT FK_COMPRA_EMPLEADO FOREIGN KEY (ID_EMPLEADO)
        REFERENCES INVENTARIO_FACTURACION.EMPLEADO(ID_EMPLEADO),
    CONSTRAINT CHK_COMPRA_TOTAL CHECK (TOTAL > 0),
    CONSTRAINT CHK_COMPRA_ESTADO CHECK (ESTADO IN ('PENDIENTE','RECIBIDA','ANULADA'))
);

-- 11. DETALLE COMPRA

CREATE TABLE INVENTARIO_FACTURACION.DETALLE_COMPRA (
    ID_DETALLE_COMPRA NUMBER PRIMARY KEY,
    ID_COMPRA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    COSTO_UNITARIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_DETALLE_COMPRA_COMPRA FOREIGN KEY (ID_COMPRA)
        REFERENCES INVENTARIO_FACTURACION.COMPRA(ID_COMPRA),
    CONSTRAINT FK_DETALLE_COMPRA_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES INVENTARIO_FACTURACION.PRODUCTO(ID_PRODUCTO),
    CONSTRAINT CHK_DET_COMPRA_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CHK_DET_COMPRA_COSTO CHECK (COSTO_UNITARIO > 0),
    CONSTRAINT CHK_DET_COMPRA_SUBTOTAL CHECK (SUBTOTAL > 0)
);

-- 12. FACTURA

CREATE TABLE INVENTARIO_FACTURACION.FACTURA (
    ID_FACTURA NUMBER PRIMARY KEY,
    NUMERO_FACTURA VARCHAR2(30) NOT NULL UNIQUE,
    FECHA_EMISION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ID_CLIENTE NUMBER,
    ID_EMPLEADO NUMBER NOT NULL,
    ID_SUCURSAL NUMBER NOT NULL,
    ID_METODO_PAGO NUMBER NOT NULL,
    TOTAL NUMBER(12,2) NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_FACTURA_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES INVENTARIO_FACTURACION.CLIENTE(ID_CLIENTE),
    CONSTRAINT FK_FACTURA_EMPLEADO FOREIGN KEY (ID_EMPLEADO)
        REFERENCES INVENTARIO_FACTURACION.EMPLEADO(ID_EMPLEADO),
    CONSTRAINT FK_FACTURA_SUCURSAL FOREIGN KEY (ID_SUCURSAL)
        REFERENCES INVENTARIO_FACTURACION.SUCURSAL(ID_SUCURSAL),
    CONSTRAINT FK_FACTURA_METODO FOREIGN KEY (ID_METODO_PAGO)
        REFERENCES INVENTARIO_FACTURACION.METODO_PAGO(ID_METODO_PAGO),
    CONSTRAINT CHK_FACTURA_TOTAL CHECK (TOTAL > 0),
    CONSTRAINT CHK_FACTURA_ESTADO CHECK (ESTADO IN ('PENDIENTE','PAGADO','ANULADO'))
);

-- 13. DETALLE FACTURA

CREATE TABLE INVENTARIO_FACTURACION.DETALLE_FACTURA (
    ID_DETALLE NUMBER PRIMARY KEY,
    ID_FACTURA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    ID_ALMACEN NUMBER NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,
    CONSTRAINT FK_DET_FACT_FACTURA FOREIGN KEY (ID_FACTURA)
        REFERENCES INVENTARIO_FACTURACION.FACTURA(ID_FACTURA),
    CONSTRAINT FK_DET_FACT_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES INVENTARIO_FACTURACION.PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_DET_FACT_ALMACEN FOREIGN KEY (ID_ALMACEN)
        REFERENCES INVENTARIO_FACTURACION.ALMACEN(ID_ALMACEN),
    CONSTRAINT CHK_DET_FACT_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CHK_DET_FACT_PRECIO CHECK (PRECIO_UNITARIO > 0),
    CONSTRAINT CHK_DET_FACT_SUBTOTAL CHECK (SUBTOTAL > 0)
);

-- 14. MOVIMIENTO INVENTARIO

CREATE TABLE INVENTARIO_FACTURACION.MOVIMIENTO_INVENTARIO (
    ID_MOVIMIENTO NUMBER PRIMARY KEY,
    ID_PRODUCTO NUMBER NOT NULL,
    ID_ALMACEN NUMBER NOT NULL,
    ID_EMPLEADO NUMBER,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    REFERENCIA VARCHAR2(100),
    CONSTRAINT FK_MOV_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES INVENTARIO_FACTURACION.PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_MOV_ALMACEN FOREIGN KEY (ID_ALMACEN)
        REFERENCES INVENTARIO_FACTURACION.ALMACEN(ID_ALMACEN),
    CONSTRAINT FK_MOV_EMPLEADO FOREIGN KEY (ID_EMPLEADO)
        REFERENCES INVENTARIO_FACTURACION.EMPLEADO(ID_EMPLEADO),
    CONSTRAINT CHK_MOV_TIPO CHECK (
        TIPO IN ('ENTRADA','SALIDA','VENTA','COMPRA','DEVOLUCION','AJUSTE')
    ),
    CONSTRAINT CHK_MOV_CANTIDAD CHECK (CANTIDAD > 0)
);

-- 15. BITACORA

CREATE TABLE INVENTARIO_FACTURACION.BITACORA (
    ID_BITACORA NUMBER PRIMARY KEY,
    ID_EMPLEADO NUMBER,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACCION VARCHAR2(60) NOT NULL,
    TABLA_AFECTADA VARCHAR2(60) NOT NULL,
    ID_REGISTRO NUMBER,
    DESCRIPCION VARCHAR2(255),
    CONSTRAINT FK_BITACORA_EMPLEADO FOREIGN KEY (ID_EMPLEADO)
        REFERENCES INVENTARIO_FACTURACION.EMPLEADO(ID_EMPLEADO)
);
